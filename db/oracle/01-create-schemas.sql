-- Manual bootstrap (sqlplus as SYSDBA / SYSTEM).
-- Init scripts for Docker must target FREEPDB1 — SYS starts connected to CDB FREE.
--
--   sqlplus sys/<password>@//localhost:1521/FREE as sysdba
--   @db/oracle/01-create-schemas.sql
--
-- Or against an already-open PDB session:
--   ALTER SESSION SET CONTAINER = FREEPDB1;

ALTER SESSION SET CONTAINER = FREEPDB1;

WHENEVER SQLERROR CONTINUE

CREATE USER camunda_service IDENTIFIED BY "Camunda_Pass_1"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

CREATE USER governance_service IDENTIFIED BY "Governance_Pass_1"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

CREATE USER refund_service IDENTIFIED BY "Refund_Pass_1"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

CREATE USER document_service IDENTIFIED BY "Document_Pass_1"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

CREATE USER registration_service IDENTIFIED BY "Registration_Pass_1"
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

-- CONNECT alone is not always enough; grant CREATE SESSION explicitly.
GRANT CREATE SESSION, CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TABLE, CREATE TRIGGER, CREATE TYPE TO camunda_service;
GRANT CREATE SESSION, CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TABLE, CREATE TRIGGER TO governance_service;
GRANT CREATE SESSION, CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TABLE, CREATE TRIGGER TO refund_service;
GRANT CREATE SESSION, CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TABLE, CREATE TRIGGER TO registration_service;
GRANT CREATE SESSION, CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TABLE, CREATE TRIGGER TO document_service;

ALTER USER camunda_service QUOTA UNLIMITED ON users;
ALTER USER governance_service QUOTA UNLIMITED ON users;
ALTER USER refund_service QUOTA UNLIMITED ON users;
ALTER USER registration_service QUOTA UNLIMITED ON users;
ALTER USER document_service QUOTA UNLIMITED ON users;
